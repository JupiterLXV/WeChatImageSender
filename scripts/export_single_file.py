#!/usr/bin/env python3
"""Export an optional standalone Python entry point from the maintained modules."""
from __future__ import annotations

import argparse
import ast
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = [
    'wechat_sender/image_utils.py', 'wechat_sender/clipboard_win32.py',
    'wechat_sender/accessibility.py', 'wechat_sender/windows_ocr.py', 'wechat_sender/capture_win32.py', 'wechat_sender/wechat_adapter.py',
    'wechat_sender/job_store.py', 'wechat_sender/gui_layout.py',
    'wechat_sender/gui_workflow.py', 'wechat_sender/gui.py', 'main.py',
]


class InlineInternalImports(ast.NodeTransformer):
    def visit_ImportFrom(self, node):
        if node.module == '__future__':
            return None
        module = node.module or ''
        if node.level or module == 'wechat_sender' or module.startswith('wechat_sender.'):
            # The imported definitions already exist in the merged namespace,
            # but local aliases (such as recognize_local_text) still need binding.
            return [
                ast.copy_location(
                    ast.Assign(
                        targets=[ast.Name(id=alias.asname, ctx=ast.Store())],
                        value=ast.Name(id=alias.name, ctx=ast.Load()),
                    ),
                    node,
                )
                for alias in node.names
                if alias.asname and alias.asname != alias.name
            ] or None
        return node


def export(destination: Path) -> Path:
    destination = destination.resolve()
    destination.mkdir(parents=True, exist_ok=True)
    chunks = ['#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n',
              '# Generated by scripts/export_single_file.py; edit modules instead.\n',
              'from __future__ import annotations\n']
    for module in MODULES:
        tree = InlineInternalImports().visit(ast.parse((ROOT / module).read_text(encoding='utf-8')))
        ast.fix_missing_locations(tree)
        chunks.append(f'\n# ===== {module} =====\n' + ast.unparse(tree) + '\n')
    output = destination / 'WeChatImageSender_v3.py'
    content = ''.join(chunks)
    compile(content, str(output), 'exec')
    output.write_text(content, encoding='utf-8')
    shutil.copytree(ROOT / 'assets', destination / 'assets', dirs_exist_ok=True)
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'dist' / 'standalone')
    args = parser.parse_args()
    print(export(args.output))
